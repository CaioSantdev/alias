create table if not exists public.aliases (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  shortcut text not null check (char_length(shortcut) between 2 and 40 and left(shortcut, 1) = '-'),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, shortcut)
);

alter table public.aliases enable row level security;

drop policy if exists "Users can read their own aliases" on public.aliases;
drop policy if exists "Users can insert their own aliases" on public.aliases;
drop policy if exists "Users can update their own aliases" on public.aliases;
drop policy if exists "Users can delete their own aliases" on public.aliases;

create policy "Users can read their own aliases" on public.aliases for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users can insert their own aliases" on public.aliases for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users can update their own aliases" on public.aliases for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users can delete their own aliases" on public.aliases for delete to authenticated using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.aliases to authenticated;
grant usage, select on sequence public.aliases_id_seq to authenticated;
